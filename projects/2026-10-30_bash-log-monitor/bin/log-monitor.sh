#!/bin/bash

# Log Monitoring & Alert System
# Monitors log files and triggers alerts based on configurable rules
# Usage: ./log-monitor.sh [--config CONFIG_FILE] [--dry-run]

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONFIG_FILE="${1:-${SCRIPT_DIR}/config/log-monitor.conf}"
RULES_FILE="${SCRIPT_DIR}/config/alert-rules.conf"
DRY_RUN="${DRY_RUN:-false}"

# Default configuration
ALERT_EMAIL="${ALERT_EMAIL:-root@localhost}"
ALERT_DIR="${ALERT_DIR:-${SCRIPT_DIR}/alerts}"
STATE_FILE="${ALERT_DIR}/.last-check"
LOG_MONITOR_LOG="${LOG_MONITOR_LOG:-${ALERT_DIR}/log-monitor.log}"
HOSTNAME="${HOSTNAME:-$(hostname)}"

# Colors for output
RED='\033[0;31m'
YELLOW='\033[1;33m'
GREEN='\033[0;32m'
NC='\033[0m' # No Color

# Initialize
mkdir -p "${ALERT_DIR}"
touch "${STATE_FILE}"

# Logging function
log_event() {
    local level="$1"
    shift
    local message="$*"
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] [$level] $message" >> "${LOG_MONITOR_LOG}"
    if [[ "$level" == "ERROR" ]]; then
        echo -e "${RED}[ERROR]${NC} $message" >&2
    elif [[ "$level" == "WARNING" ]]; then
        echo -e "${YELLOW}[WARNING]${NC} $message" >&2
    elif [[ "$level" == "INFO" ]]; then
        echo -e "${GREEN}[INFO]${NC} $message" >&2
    fi
}

# Validate configuration
validate_config() {
    if [[ ! -f "$CONFIG_FILE" ]]; then
        log_event ERROR "Configuration file not found: $CONFIG_FILE"
        return 1
    fi

    if [[ ! -f "$RULES_FILE" ]]; then
        log_event ERROR "Rules file not found: $RULES_FILE"
        return 1
    fi

    log_event INFO "Configuration loaded from $CONFIG_FILE"
    return 0
}

# Source configuration files
source_config() {
    # Source the config file if it exists
    if [[ -f "$CONFIG_FILE" ]]; then
        # shellcheck source=/dev/null
        source "$CONFIG_FILE"
    fi

    # Ensure required variables are set
    LOGS_TO_MONITOR="${LOGS_TO_MONITOR:-/var/log/syslog}"
    ALERT_EMAIL="${ALERT_EMAIL:-root@localhost}"
}

# Read rules from configuration file
read_rules() {
    local rules=()

    if [[ ! -f "$RULES_FILE" ]]; then
        log_event WARNING "Rules file not found: $RULES_FILE"
        return 1
    fi

    while IFS= read -r line; do
        # Skip comments and empty lines
        [[ "$line" =~ ^#.*$ ]] && continue
        [[ -z "$line" ]] && continue

        rules+=("$line")
    done < "$RULES_FILE"

    printf '%s\n' "${rules[@]}"
}

# Get the last check time
get_last_check() {
    if [[ -f "$STATE_FILE" ]]; then
        cat "$STATE_FILE" 2>/dev/null || echo "0"
    else
        echo "0"
    fi
}

# Update last check time
update_last_check() {
    date +%s > "$STATE_FILE"
}

# Check if log file needs checking
should_check_log() {
    local log_file="$1"

    if [[ ! -f "$log_file" ]]; then
        log_event WARNING "Log file not found: $log_file"
        return 1
    fi

    return 0
}

# Process a single log file
process_log_file() {
    local log_file="$1"
    local rules_output="$2"
    local last_check="$3"

    local alert_count=0
    local matches=""

    while IFS= read -r rule; do
        [[ -z "$rule" ]] && continue

        # Check if this is an exclusion rule (starts with !)
        if [[ "$rule" == "!"* ]]; then
            continue
        fi

        # Check if file modification time is after last check
        local file_mtime=$(stat -f "%m" "$log_file" 2>/dev/null || stat -c "%Y" "$log_file" 2>/dev/null || echo 0)

        if [[ "$file_mtime" -gt "$last_check" ]]; then
            # Find matches in the log file
            local grep_matches
            grep_matches=$(grep -nE "$rule" "$log_file" 2>/dev/null | tail -20 || true)

            if [[ -n "$grep_matches" ]]; then
                alert_count=$((alert_count + 1))
                matches="${matches}${log_file}:${rule}${grep_matches}\n"
            fi
        fi
    done <<< "$rules_output"

    if [[ $alert_count -gt 0 ]]; then
        return 0
    else
        return 1
    fi
}

# Generate alert message
generate_alert() {
    local log_file="$1"
    local matches="$2"
    local timestamp=$(date '+%Y-%m-%d %H:%M:%S')

    cat <<EOF
Log Monitoring Alert
====================
Hostname: $HOSTNAME
Timestamp: $timestamp
Log File: $log_file

Matches Found:
--------------
$(echo -e "$matches" | head -50)

---
Alert generated by Log Monitor v1.0
Rules file: $RULES_FILE
EOF
}

# Send email alert
send_alert_email() {
    local log_file="$1"
    local matches="$2"

    if [[ "$DRY_RUN" == "true" ]]; then
        log_event INFO "[DRY-RUN] Would send alert email to $ALERT_EMAIL"
        return 0
    fi

    local alert_msg
    alert_msg=$(generate_alert "$log_file" "$matches")

    # Try to send email
    if command -v mail &>/dev/null; then
        echo "$alert_msg" | mail -s "Log Alert: $log_file on $HOSTNAME" "$ALERT_EMAIL" 2>/dev/null || {
            log_event WARNING "Failed to send email to $ALERT_EMAIL"
        }
    elif command -v sendmail &>/dev/null; then
        echo "$alert_msg" | sendmail "$ALERT_EMAIL" 2>/dev/null || {
            log_event WARNING "Failed to send email via sendmail"
        }
    else
        log_event WARNING "No mail command found (mail or sendmail required)"
    fi

    log_event INFO "Alert sent for $log_file"
}

# Archive alert to file
archive_alert() {
    local log_file="$1"
    local matches="$2"

    local alert_file="${ALERT_DIR}/$(date '+%Y%m%d_%H%M%S')_$(basename "$log_file").alert"

    {
        echo "=== Alert at $(date '+%Y-%m-%d %H:%M:%S') ==="
        echo "Log File: $log_file"
        echo "Hostname: $HOSTNAME"
        echo ""
        echo "$matches"
        echo ""
    } >> "$alert_file"

    log_event INFO "Alert archived to $alert_file"
}

# Main monitoring function
main() {
    log_event INFO "Starting log monitor on $HOSTNAME"

    # Validate and source configuration
    if ! validate_config; then
        log_event ERROR "Configuration validation failed"
        return 1
    fi

    source_config

    # Read rules
    local rules_output
    rules_output=$(read_rules)

    if [[ -z "$rules_output" ]]; then
        log_event WARNING "No rules found in $RULES_FILE"
        return 0
    fi

    local last_check
    last_check=$(get_last_check)

    local alert_generated=0

    # Process each log file
    for log_file in $LOGS_TO_MONITOR; do
        if ! should_check_log "$log_file"; then
            continue
        fi

        if process_log_file "$log_file" "$rules_output" "$last_check"; then
            # Get the matches for this file
            local file_matches=""
            while IFS= read -r rule; do
                [[ "$rule" == "!"* ]] && continue
                [[ -z "$rule" ]] && continue

                local grep_output
                grep_output=$(grep -nE "$rule" "$log_file" 2>/dev/null | tail -20 || true)
                if [[ -n "$grep_output" ]]; then
                    file_matches="${file_matches}Rule: $rule\n$grep_output\n"
                fi
            done <<< "$rules_output"

            # Send alert
            send_alert_email "$log_file" "$file_matches"
            archive_alert "$log_file" "$file_matches"
            alert_generated=1
        fi
    done

    # Update last check time
    update_last_check

    if [[ $alert_generated -eq 0 ]]; then
        log_event INFO "Monitoring completed - no alerts triggered"
    fi

    log_event INFO "Log monitor check completed"
    return 0
}

# Error handling
trap 'log_event ERROR "Script interrupted"; exit 130' INT TERM

# Run main function
main "$@"
exit $?
